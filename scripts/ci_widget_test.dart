import 'package:flutter/material.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:shared_preferences/shared_preferences.dart';
import 'package:nivora_booking/main.dart';
import 'package:nivora_booking/state/booking_controller.dart';

void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  testWidgets('Nivora boots and switches to the explore/search screen',
      (WidgetTester tester) async {
    SharedPreferences.setMockInitialValues({});
    final controller = BookingController();
    await controller.initialize();
    addTearDown(controller.dispose);

    // NivoraApp is the real root widget; the autogenerated Flutter template's
    // MyApp constructor does not exist in this project.
    await tester.pumpWidget(NivoraApp(controller: controller));
    expect(find.byType(MaterialApp), findsOneWidget);
    expect(find.text('Jelajah'), findsOneWidget);
    expect(find.text('Cari'), findsOneWidget);

    await tester.tap(find.text('Cari'));
    await tester.pump();
    expect(find.text('Cari & temukan'), findsOneWidget);
  });
}
